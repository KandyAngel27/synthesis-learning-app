#!/usr/bin/env node
// ============================================
// SYNTHESIS — book "added on" map generator
//
// Books carry no dateAdded field, so "What's New" had nothing real to sort by.
// Git does know: every external book module was added in some commit. This
// walks the module script tags in index.html, asks git when each file first
// appeared, and writes that out as a lookup the app can read at runtime.
//
// Books that still live inline in data.js get no entry — there is no per-book
// date to recover for them. That is fine: What's New falls back for those, and
// new books all ship as external modules anyway (see CLAUDE.md).
//
// Usage:  node tools/gen-book-added-on.cjs        # rewrites book-added-on-data.js
//         node tools/gen-book-added-on.cjs --dry  # print, write nothing
// ============================================

'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'book-added-on-data.js');
const DRY = process.argv.includes('--dry');

// Script tags loaded before data.js are the external book modules.
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const tags = html.split('\n')
    .map(l => (l.match(/<script src="([^"?]+)/) || [])[1])
    .filter(Boolean);
const dataIdx = tags.indexOf('data.js');
const moduleFiles = tags.slice(0, dataIdx).filter(f => /-data\.js$/.test(f));

function gitAddedOn(file) {
    try {
        const out = execFileSync('git',
            ['log', '--diff-filter=A', '--format=%aI', '-1', '--', file],
            { cwd: ROOT, encoding: 'utf8' }).trim();
        return out ? out.slice(0, 10) : null;   // YYYY-MM-DD
    } catch {
        return null;
    }
}

// Run a module in isolation and collect every book id it introduces — a file
// may define a single book or a whole category of them.
function bookIdsIn(file) {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) return [];
    const sandbox = { window: {} };
    sandbox.window = sandbox;
    sandbox.globalThis = sandbox;
    vm.createContext(sandbox);
    try { vm.runInContext(fs.readFileSync(full, 'utf8'), sandbox, { filename: file }); } catch { return []; }

    const ids = [];
    const visit = v => {
        if (!v || typeof v !== 'object') return;
        if (Array.isArray(v)) return v.forEach(visit);
        if (typeof v.id === 'string' && Array.isArray(v.lessonList)) ids.push(v.id);
        if (Array.isArray(v.books)) v.books.forEach(visit);
    };
    for (const key of Object.keys(sandbox)) {
        if (key === 'window' || key === 'globalThis') continue;
        visit(sandbox[key]);
    }
    return ids;
}

const map = {};
let filesWithDate = 0, filesWithout = 0;
for (const file of moduleFiles) {
    const date = gitAddedOn(file);
    const ids = bookIdsIn(file);
    if (!ids.length) continue;
    if (!date) { filesWithout++; continue; }
    filesWithDate++;
    // A file's date applies to every book it introduces. If two files claim the
    // same id, keep the earlier date — that is when the book first appeared.
    for (const id of ids) {
        if (!map[id] || date < map[id]) map[id] = date;
    }
}

const sorted = Object.keys(map).sort((a, b) => (map[b].localeCompare(map[a])) || a.localeCompare(b));
const body = {};
sorted.forEach(id => { body[id] = map[id]; });

const header = '// ============================================\n'
    + '// SYNTHESIS — when each external book module was added, from git history.\n'
    + '// Generated by tools/gen-book-added-on.cjs — do not hand-edit.\n'
    + '// getWhatsNewBooks() sorts on this; books absent here simply do not\n'
    + '// claim to be new. Regenerate after adding a book (and after it is\n'
    + '// committed, since the date comes from the commit that added the file).\n'
    + '// ============================================\n'
    + 'window.BOOK_ADDED_ON = ';

const out = header + JSON.stringify(body, null, 1) + ';\n';

console.log('module files scanned : ' + moduleFiles.length);
console.log('files with a git date: ' + filesWithDate);
console.log('files without        : ' + filesWithout + '  (uncommitted — no entry emitted)');
console.log('book ids mapped      : ' + sorted.length);
console.log('newest 7             :');
sorted.slice(0, 7).forEach(id => console.log('   ' + map[id] + '  ' + id));

if (DRY) { console.log('\n--dry: nothing written'); process.exit(0); }
fs.writeFileSync(OUT, out, 'utf8');
new vm.Script(out);
console.log('\nWROTE ' + path.relative(ROOT, OUT) + '  (' + Math.round(out.length / 1024) + ' KB)');
